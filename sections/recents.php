<script>
// Featured Slider - Auto-slide with Touch/Pinch Support
document.addEventListener('DOMContentLoaded', function() {
    const slider = document.querySelector('.feat-slider-wrapper');
    const slides = document.querySelectorAll('.feat-slide');
    const dots = document.querySelectorAll('.feat-dot');
    let currentIndex = 0;
    const totalSlides = slides.length;
    let autoplayInterval;
    let isTransitioning = false;

    // Go to specific slide
    function goToSlide(index) {
        if (isTransitioning) return;
        if (index < 0) index = totalSlides - 1;
        if (index >= totalSlides) index = 0;
        
        isTransitioning = true;
        currentIndex = index;
        const translateX = -currentIndex * 100;
        slider.style.transform = 'translateX(' + translateX + '%)';
        
        // Update dots
        dots.forEach(function(dot, i) {
            if (i === currentIndex) {
                dot.classList.add('active');
            } else {
                dot.classList.remove('active');
            }
        });
        
        setTimeout(function() {
            isTransitioning = false;
        }, 800);
    }

    // Next slide
    function nextSlide() {
        goToSlide(currentIndex + 1);
    }

    // Previous slide
    function prevSlide() {
        goToSlide(currentIndex - 1);
    }

    // Start autoplay
    function startAutoplay() {
        if (autoplayInterval) {
            clearInterval(autoplayInterval);
            autoplayInterval = null;
        }
        autoplayInterval = setInterval(nextSlide, 5000);
    }

    // Stop autoplay
    function stopAutoplay() {
        if (autoplayInterval) {
            clearInterval(autoplayInterval);
            autoplayInterval = null;
        }
    }

    // Dot click event
    dots.forEach(function(dot) {
        dot.addEventListener('click', function() {
            stopAutoplay();
            var index = parseInt(this.getAttribute('data-index'));
            goToSlide(index);
            startAutoplay();
        });
        
        // Touch support for dots
        dot.addEventListener('touchstart', function(e) {
            e.preventDefault();
            stopAutoplay();
            var index = parseInt(this.getAttribute('data-index'));
            goToSlide(index);
            startAutoplay();
        }, { passive: false });
    });

    // Pause on hover (desktop only)
    var container = document.querySelector('.feat-slider-container');
    if (container) {
        container.addEventListener('mouseenter', stopAutoplay);
        container.addEventListener('mouseleave', startAutoplay);
    }

    // ==========================================
    // TOUCH / SWIPE SUPPORT
    // ==========================================
    var touchStartX = 0;
    var touchStartY = 0;
    var touchEndX = 0;
    var touchEndY = 0;
    var isSwiping = false;

    if (slider) {
        slider.addEventListener('touchstart', function(e) {
            var touches = e.touches;
            if (touches.length === 1) {
                touchStartX = touches[0].screenX;
                touchStartY = touches[0].screenY;
                isSwiping = true;
                stopAutoplay();
            }
        }, { passive: true });

        slider.addEventListener('touchmove', function(e) {
            if (!isSwiping) return;
            var touches = e.touches;
            if (touches.length !== 1) return;
            
            var touchMoveX = touches[0].screenX;
            var touchMoveY = touches[0].screenY;
            var diffX = Math.abs(touchMoveX - touchStartX);
            var diffY = Math.abs(touchMoveY - touchStartY);
            
            if (diffX > diffY && diffX > 10) {
                e.preventDefault();
            }
        }, { passive: false });

        slider.addEventListener('touchend', function(e) {
            if (!isSwiping) {
                isSwiping = false;
                return;
            }
            
            var touch = e.changedTouches[0];
            if (touch) {
                touchEndX = touch.screenX;
                touchEndY = touch.screenY;
                handleSwipe();
            }
            
            isSwiping = false;
            startAutoplay();
        }, { passive: true });

        slider.addEventListener('touchcancel', function() {
            isSwiping = false;
            startAutoplay();
        }, { passive: true });
    }

    // Handle swipe gesture
    function handleSwipe() {
        var swipeThreshold = 50;
        var diffX = touchStartX - touchEndX;
        var diffY = Math.abs(touchStartY - touchEndY);
        
        if (Math.abs(diffX) > swipeThreshold && diffY < 100) {
            if (diffX > 0) {
                nextSlide();
            } else {
                prevSlide();
            }
        }
    }

    // ==========================================
    // KEYBOARD NAVIGATION
    // ==========================================
    document.addEventListener('keydown', function(e) {
        var rect = container ? container.getBoundingClientRect() : null;
        if (!rect) return;
        var isVisible = rect.bottom > 0 && rect.top < window.innerHeight;
        
        if (isVisible) {
            if (e.key === 'ArrowLeft') {
                e.preventDefault();
                stopAutoplay();
                prevSlide();
                startAutoplay();
            } else if (e.key === 'ArrowRight') {
                e.preventDefault();
                stopAutoplay();
                nextSlide();
                startAutoplay();
            }
        }
    });

    // ==========================================
    // WINDOW RESIZE HANDLER
    // ==========================================
    var resizeTimeout;
    window.addEventListener('resize', function() {
        clearTimeout(resizeTimeout);
        resizeTimeout = setTimeout(function() {
            goToSlide(currentIndex);
        }, 250);
    });

    // ==========================================
    // VISIBILITY CHANGE - Pause when tab hidden
    // ==========================================
    document.addEventListener('visibilitychange', function() {
        if (document.hidden) {
            stopAutoplay();
        } else {
            startAutoplay();
        }
    });

    // ==========================================
    // INITIALIZE
    // ==========================================
    goToSlide(0);
    startAutoplay();

    // ==========================================
    // CLEANUP
    // ==========================================
    window.addEventListener('beforeunload', function() {
        stopAutoplay();
    });
});
</script>