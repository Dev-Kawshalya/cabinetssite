        '.faq-item .faq-question',
        '.faq-item .faq-answer',
        '.process-step',
        '.process-step .step-number'
    ];
    
    // Join selectors
    const allSelectors = selectors.join(', ');
    
    // Get all elements
    const elements = document.querySelectorAll(allSelectors);
    
    // Observer options
    const observerOptions = {
        root: null,
        rootMargin: '0px 0px -30px 0px',
        threshold: 0.1
    };
    
    // Observer callback
    const observerCallback = function(entries, observer) {
        entries.forEach(function(entry) {
            if (entry.isIntersecting) {
                entry.target.classList.add('is-visible');
                // Unobserve after animation to improve performance
                observer.unobserve(entry.target);
            }
        });
    };
    
    // Create observer
    const observer = new IntersectionObserver(observerCallback, observerOptions);
    
    // Observe each element
    elements.forEach(function(element) {
        observer.observe(element);
    });
    
    // ==========================================
    // HANDLE DYNAMIC CONTENT (AJAX/JS added)
    // ==========================================
    
    // Function to observe new elements
    function observeNewElements() {
        const newElements = document.querySelectorAll(allSelectors + ':not(.observed)');
        newElements.forEach(function(element) {
            element.classList.add('observed');
            observer.observe(element);
        });
    }
    
    // Observe DOM changes for new content
    const mutationObserver = new MutationObserver(function(mutations) {
        mutations.forEach(function(mutation) {
            if (mutation.addedNodes.length > 0) {
                observeNewElements();
            }
        });
    });
    
    // Start observing
    mutationObserver.observe(document.body, {
        childList: true,
        subtree: true
    });
    
