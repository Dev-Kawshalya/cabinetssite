                setTimeout(function() {
                    el.classList.add('is-visible');
                }, 100);
            });
        }
    }
    
    // Trigger on page load
    setTimeout(triggerHeroSlideAnimations, 500);
    
    // Trigger when slide changes (if using slider)
    const sliderDots = document.querySelectorAll('.hero-slider__dot');
    sliderDots.forEach(function(dot) {
        dot.addEventListener('click', function() {
            setTimeout(triggerHeroSlideAnimations, 600);
        });
    });
    
    // ==========================================
    // CLEANUP
    // ==========================================
    
    // Cleanup on page unload
    window.addEventListener('beforeunload', function() {
        mutationObserver.disconnect();
        observer.disconnect();
    });
    
